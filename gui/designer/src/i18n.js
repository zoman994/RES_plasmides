let currentLang = 'ru';

/** Set active language ('en' or 'ru'). */
export function setLang(lang) { currentLang = lang; }

/** Get active language. */
export function getLang() { return currentLang; }

/** Translate a key. Fallback: en value → key itself. */
export function t(key) {
  return TRANSLATIONS[currentLang]?.[key]
    || TRANSLATIONS.en?.[key]
    || key;
}

/** Translate and substitute simple `{name}` placeholders. */
export function tf(key, values = {}) {
  return t(key).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  ));
}

export default TRANSLATIONS;
